static void draw_char(uint8_t *fb, int x, int y, char c, uint8_t color) {
    if (c < 32 || c > 126) return;
    const uint8_t *glyph = font5x7[c - 32];
    for (int col = 0; col < 5; col++) {
        uint8_t bits = glyph[col];
        for (int row = 0; row < 7; row++) {
            if (bits & (1 << row)) {
                int px = x + col;
                int py = y + row;
                if (px >= 0 && px < FRAME_WIDTH && py >= 0 && py < FRAME_HEIGHT) {
                    fb[py * FRAME_WIDTH + px] = color;
                }
            }
        }
    }
}

void missing_rom_screen_draw_string(uint8_t *fb, int x, int y, const char *str, uint8_t color) {
    int cur_x = x;
    while (*str) {
        draw_char(fb, cur_x, y, *str, color);
        cur_x += 6;
        str++;
    }
}

void missing_rom_screen_render_dialog(uint8_t *fb, const char *title, const char *path,
                                      const char **files, uint32_t file_count, uint32_t frame_count) {
    memset(fb, COLOR_BLACK, FRAME_WIDTH * FRAME_HEIGHT);

    uint8_t header_color = (frame_count & 32) ? COLOR_RED : COLOR_YELLOW;

    missing_rom_screen_draw_string(fb, 24, 20, "========================================", COLOR_WHITE);
    missing_rom_screen_draw_string(fb, 36, 32, title ? title : "** ARCADE ROMS REQUIRED **", header_color);
    missing_rom_screen_draw_string(fb, 24, 44, "========================================", COLOR_WHITE);

    missing_rom_screen_draw_string(fb, 20, 62, "Please place ROM files in directory:", COLOR_CYAN);
    if (path) {
        missing_rom_screen_draw_string(fb, 36, 74, path, COLOR_YELLOW);
    }

    missing_rom_screen_draw_string(fb, 20, 94, "Required ROM files:", COLOR_WHITE);
    int cur_y = 106;
    for (uint32_t i = 0; i < file_count && i < 5; i++) {
        if (files[i]) {
            missing_rom_screen_draw_string(fb, 30, cur_y, files[i], COLOR_GREEN);
            cur_y += 12;
        }
    }

    missing_rom_screen_draw_string(fb, 20, 168, "Then rebuild & flash the firmware image.", COLOR_CYAN);
    missing_rom_screen_draw_string(fb, 24, 188, "========================================", COLOR_WHITE);
    missing_rom_screen_draw_string(fb, 30, 200, "RP2350 HSTX HDMI Engine: 60.00Hz Active", COLOR_WHITE);
    missing_rom_screen_draw_string(fb, 24, 212, "========================================", COLOR_WHITE);
}
